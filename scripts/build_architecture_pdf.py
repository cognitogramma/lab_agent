def figure(name: str, caption: str) -> str:
    """Embed a PNG by data URI, or say plainly that it was not there."""
    path = paths.runs_dir() / "figures" / name
    if not path.exists():
        return (
            f'<p class="caption warn">[figure {name} not present; regenerate it '
            f"with polyrmc, then rebuild this document]</p>"
        )
    encoded = base64.b64encode(path.read_bytes()).decode("ascii")
    return (
        f'<img src="data:image/png;base64,{encoded}" width="480"/>'
        f'<p class="caption">{caption}</p>'
    )


